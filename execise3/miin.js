// 1 fruit

let fruit = "Apple";

switch (fruit) {
    case "Apple":
        console.log("Apples are $2.5");
        break;
    case "Mangoes":
        console.log("Mangoes are $1.5");
        break;
    case "Banana":
        console.log("Bananas are $1");
        break;
    case "Orange":
        console.log("Oranges are $2");
        break;
    default:
        console.log("Fruit is not available");
}
